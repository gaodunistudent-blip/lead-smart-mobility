window.currentLanguage = localStorage.getItem('lead_language') || 'en';

window.t = (key) => translations[window.currentLanguage]?.[key] || translations.en[key] || key;

window.setLanguage = (language) => {
    window.currentLanguage = translations[language] ? language : 'en';
    localStorage.setItem('lead_language', window.currentLanguage);
    document.documentElement.lang = window.currentLanguage;

    ['setting-language', 'reg-language'].forEach((id) => {
        const select = document.getElementById(id);
        if (select) select.value = window.currentLanguage;
    });

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const translation = window.t(element.dataset.i18n);
        if (translation !== element.dataset.i18n) {
            element.textContent = translation;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const translation = window.t(element.dataset.i18nPlaceholder);
        if (translation !== element.dataset.i18nPlaceholder) {
            element.placeholder = translation;
        }
    });
};

window.initializeLanguage = () => {
    const savedLanguage = localStorage.getItem('lead_language');
    window.setLanguage(savedLanguage || window.currentLanguage);
};
